# Build the Android bridge (android/rust-bridge) for arm64: the JNI cdylib
# (libcrate_jni.so, via cargo-ndk) and the headless boot-test binary (via
# cargo --target). The engine comes from Scripts/android-fetch-engine.sh
# (pinned tag + commit, Android patches applied); the link finds libslirp
# through SLIRP_LIB_DIR, which crate-host's own build.rs honours.
#
#     ./Scripts/android-build-engine.sh            # both artifacts
#     ./Scripts/android-build-engine.sh bin-only   # just crate-boot-test
#     ./Scripts/android-build-engine.sh so-only    # just libcrate_jni.so
#
# Needs the NDK (SDK Manager), the aarch64-linux-android Rust target,
# cargo-ndk, and Scripts/android-build-native.sh's output (libslirp) for the
# link. Writes a target-scoped .cargo/config.toml (gitignored) with the
# absolute NDK linker path, so the host build is untouched. Outputs land in
# android/libs/arm64-v8a/.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BRIDGE="$REPO/android/rust-bridge"
OUT="$REPO/android/libs/arm64-v8a"
TARGET=aarch64-linux-android
MIN_ANDROID=33
MODE="${1:-all}"

./Scripts/android-fetch-engine.sh

NDK_DIR="${NDK_DIR:-$HOME/Library/Android/sdk/ndk/30.0.16248370}"
[ -d "$NDK_DIR" ] || { echo "no NDK at $NDK_DIR (set NDK_DIR)" >&2; exit 1; }
TC="$NDK_DIR/toolchains/llvm/prebuilt/darwin-x86_64/bin"
[ -f "$OUT/libslirp.so" ] || {
    echo "no $OUT/libslirp.so: run Scripts/android-build-native.sh first" >&2; exit 1; }

mkdir -p "$BRIDGE/.cargo"
cat > "$BRIDGE/.cargo/config.toml" <<CONFIG
# Generated by Scripts/android-build-engine.sh. Do not commit.
[target.$TARGET]
linker = "$TC/aarch64-linux-android$MIN_ANDROID-clang"
CONFIG

export SLIRP_LIB_DIR="$OUT"
# The NDK linker: .cargo/config.toml above (found through the working
# directory) and this env var as a second way.
export CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER="$TC/aarch64-linux-android$MIN_ANDROID-clang"
export CC_aarch64_linux_android="$TC/aarch64-linux-android$MIN_ANDROID-clang"
export CXX_aarch64_linux_android="$TC/aarch64-linux-android$MIN_ANDROID-clang++"
export AR_aarch64_linux_android="$TC/llvm-ar"

if [ "$MODE" = all ] || [ "$MODE" = bin-only ]; then
    echo "==> crate-boot-test for $TARGET"
    (cd "$BRIDGE" && cargo build --release --bin crate-boot-test --target "$TARGET")
    cp -f "$BRIDGE/target/$TARGET/release/crate-boot-test" "$OUT/"
fi

if [ "$MODE" = all ] || [ "$MODE" = so-only ]; then
    echo "==> libcrate_jni.so for $TARGET"
    (cd "$BRIDGE" && cargo ndk --platform "$MIN_ANDROID" --target "$TARGET" \
        build --release --lib)
    cp -f "$BRIDGE/target/$TARGET/release/libcrate_jni.so" "$OUT/"
    # The bridge must carry the engine, not merely declare it: rustc omits
    # an rlib nothing references, which would leave crate_* undefined and
    # fail only at System.loadLibrary on device. Fail here instead.
    if "$TC/llvm-nm" --dynamic --undefined-only "$OUT/libcrate_jni.so" \
        | grep -q "crate_"; then
        echo "libcrate_jni.so has undefined crate_* symbols (engine not linked)" >&2
        exit 1
    fi
    # Stage what the Gradle app consumes: the JNI library as jniLibs, the
    # versioned glib/slirp binaries as assets (System.load by absolute path).
    JNIDIR="$REPO/android/app/src/main/jniLibs/arm64-v8a"
    ASSETDIR="$REPO/android/app/src/main/assets/native"
    mkdir -p "$JNIDIR" "$ASSETDIR"
    cp -f "$OUT/libcrate_jni.so" "$JNIDIR/"
    cp -f "$OUT"/libglib-2.0.so.0.9000.1 "$OUT"/libslirp.so.0.4.0 "$ASSETDIR/"
fi

"$TC/llvm-readelf" -d "$OUT"/crate-boot-test 2>/dev/null | grep -m5 NEEDED || true
echo "engine artifacts in $OUT/"
